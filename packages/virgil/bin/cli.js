#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');

const TEMPLATE = path.join(__dirname, '..', 'templates', 'AGENTS.md');
const TARGET = path.join(process.cwd(), 'AGENTS.md');

const command = process.argv[2];

const commands = {
  init() {
    if (fs.existsSync(TARGET) && !process.argv.includes('--force')) {
      console.error('AGENTS.md already exists. Use --force to overwrite.');
      process.exit(1);
    }

    if (!fs.existsSync(TEMPLATE)) {
      console.error('Template not found. Package may be corrupted.');
      process.exit(1);
    }

    fs.copyFileSync(TEMPLATE, TARGET);

    const size = (fs.statSync(TARGET).size / 1024).toFixed(1);
    console.log(`AGENTS.md created (${size} KB)`);
    console.log('Your AI agent now has a methodology. Open it and start working.');
  },

  scan() {
    const { scan } = require('../lib/scan');
    const audit = process.argv.includes('--audit');
    const inject = process.argv.includes('--inject');
    const cwd = process.cwd();

    const output = scan(cwd, { audit });

    if (inject) {
      if (!fs.existsSync(TARGET)) {
        console.error('AGENTS.md not found in current directory. Run "virgil init" first, or use "virgil scan" without --inject.');
        process.exit(1);
      }

      const existing = fs.readFileSync(TARGET, 'utf-8');
      const marker = '## Project Context (generated by virgil scan)';

      let updated;
      if (existing.includes(marker)) {
        // Replace existing scan section (everything from marker to next ## or end of file)
        const markerIndex = existing.indexOf(marker);
        const afterMarker = existing.substring(markerIndex + marker.length);
        // Find next ## heading that is NOT part of scan output (### subsections are part of scan)
        const nextH2 = afterMarker.search(/\n## (?!#)/);
        if (nextH2 !== -1) {
          updated = existing.substring(0, markerIndex) + output + afterMarker.substring(nextH2);
        } else {
          updated = existing.substring(0, markerIndex) + output;
        }
      } else {
        updated = existing.trimEnd() + '\n\n' + output;
      }

      fs.writeFileSync(TARGET, updated);
      const size = (fs.statSync(TARGET).size / 1024).toFixed(1);
      console.log(`Scan output injected into AGENTS.md (${size} KB)`);
    } else {
      console.log(output);
    }
  },

  version() {
    const pkg = require('../package.json');
    console.log(pkg.version);
  },

  help() {
    console.log(`virgil v${require('../package.json').version}`);
    console.log('');
    console.log('Usage: virgil <command>');
    console.log('');
    console.log('Commands:');
    console.log('  init      Install AGENTS.md methodology into current project');
    console.log('  scan      Analyze codebase and output structured project context');
    console.log('  version   Show version');
    console.log('  help      Show this help');
    console.log('');
    console.log('Options:');
    console.log('  --force   Overwrite existing AGENTS.md');
    console.log('  --audit   Include fastForward scoring and gap analysis (with scan)');
    console.log('  --inject  Append scan output to existing AGENTS.md (with scan)');
  },
};

const handler = commands[command] || commands[command === '--version' || command === '-v' ? 'version' : 'help'];
handler();
